def glossary_html() -> str:
    """용어 사전 대화상자용 HTML."""
    rows = "\n".join(
        f"<tr><td style='padding:6px 14px 6px 0;white-space:nowrap;'>"
        f"<b>{term}</b></td><td style='padding:6px 0;'>{desc}</td></tr>"
        for term, desc in GLOSSARY
    )
    return f"<h2>용어 사전</h2><table>{rows}</table>"


