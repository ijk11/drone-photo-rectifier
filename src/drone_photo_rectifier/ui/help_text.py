@dataclass
class GuideState:
    """단계 안내판이 판단에 쓰는 현재 상태."""

    has_image: bool = False
    n_points: int = 0
    n_distance: int = 0
    n_geometry: int = 0
    solved: bool = False
    verdict_level: str = ""
    n_outliers: int = 0
    dof: int = 0
    has_raster: bool = False


def _step(status: str, title: str, detail: str) -> str:
    return (f"<div class='step {status}'><div class='t'>{title}</div>"
            f"<div class='d'>{detail}</div></div>")


def guide_html(st: GuideState) -> str:
    """"지금 무엇을 하면 되는지"를 항상 보여 주는 안내판.

    막히는 지점이 대부분 "다음에 뭘 눌러야 하는지 모르겠다"라서, 상태에 따라
    한 단계만 강조하고 나머지는 흐리게 둔다.
    """
    parts: list[str] = []

    # 1. 사진
    if st.has_image:
        parts.append(_step("done", "✔ 1. 사진 열기", "완료"))
    else:
        parts.append(_step("now", "▶ 1. 사진 열기",
                           "<a href='act:open_image'>사진 열기</a> · "
                           "<a href='act:make_sample'>연습용 예제 만들기</a>"))
        parts.append(_step("todo", "2. 실측 거리 입력", ""))
        parts.append(_step("todo", "3. 보정 실행", ""))
        parts.append(_step("todo", "4. 결과 내보내기", ""))
        return GUIDE_CSS_WRAP % "".join(parts)

    # 2. 실측 거리
    n = st.n_distance
    if n < MIN_DISTANCES:
        parts.append(_step(
            "now", f"▶ 2. 실측 거리 입력 ({n}/{MIN_DISTANCES})",
            f"줄자로 잰 구간의 두 점을 찍고 값을 넣으세요. 최소 {MIN_DISTANCES}개가 "
            f"있어야 계산이 되고, {GOOD_DISTANCES}개부터 렌즈 왜곡까지 잡힙니다.<br>"
            "<a href='act:add_distance'>실측 거리 추가 (D)</a>"))
        parts.append(_step("todo", "3. 보정 실행", ""))
        parts.append(_step("todo", "4. 결과 내보내기", ""))
        return GUIDE_CSS_WRAP % "".join(parts)

    quality = ("충분합니다" if n >= BEST_DISTANCES
               else "렌즈 왜곡까지 잡으려면 조금 더" if n < GOOD_DISTANCES
               else "좋습니다")
    parts.append(_step("done", f"✔ 2. 실측 거리 {n}개", quality))

    # 3. 기하 구속 (선택)
    if st.n_geometry:
        parts.append(_step("done", f"✔ 3. 기하 구속 {st.n_geometry}개", "완료"))
    else:
        parts.append(_step(
            "todo", "3. 기하 구속 (선택)",
            "실제로 직각·평행인 곳이 있으면 걸어 두세요. 줄자 없이 얻는 "
            "정보라 정확도가 눈에 띄게 좋아집니다."))

    # 4. 보정
    if not st.solved:
        parts.append(_step("now", "▶ 4. 보정 실행",
                           "<a href='act:solve'>보정 실행 (F5)</a>"))
        parts.append(_step("todo", "5. 결과 내보내기", ""))
        return GUIDE_CSS_WRAP % "".join(parts)

    if st.verdict_level == "bad":
        parts.append(_step("warn", "✖ 4. 보정 실패",
                           "점 위치와 실측값 단위(미터)를 확인하고 다시 실행하세요."))
        return GUIDE_CSS_WRAP % "".join(parts)

    parts.append(_step("done", "✔ 4. 보정 완료", f"자유도 {st.dof}"))

    # 5. 진단
    if st.n_outliers:
        parts.append(_step(
            "warn", f"⚠ 5. 확인 필요 - 의심 관측 {st.n_outliers}건",
            "[관측] 탭의 빨간 줄을 확인하세요.<br>"
            "<a href='act:disable_outliers'>의심 관측 끄고 재계산</a>"))
    elif st.dof < 3:
        parts.append(_step(
            "warn", "⚠ 5. 검증이 약합니다",
            f"잉여관측이 {st.dof}개뿐이라 정확도를 확신하기 어렵습니다. "
            "실측을 몇 개 더 넣으면 좋습니다."))
    else:
        parts.append(_step("done", "✔ 5. 진단 양호", "이상 관측 없음"))

    # 6. 출력
    if st.has_raster:
        parts.append(_step("done", "✔ 6. 정사영상 생성됨",
                           "<a href='act:export'>내보내기</a>"))
    else:
        parts.append(_step("now", "▶ 6. 결과 만들기",
                           "<a href='act:preview'>정사영상 생성 / 미리보기</a>"))
    return GUIDE_CSS_WRAP % "".join(parts)



# --------------------------------------------------------------- 결과 판정
_VERDICT_COLOR = {"good": "#6fbf73", "warn": "#ffb347", "bad": "#ff7878"}


def verdict_html(v) -> str:
    """``solver.Verdict`` 를 요약창 맨 위에 넣을 HTML 로."""
    color = _VERDICT_COLOR.get(v.level, "#9aa4ad")
    items = "".join(f"<li>{a}</li>" for a in v.advice)
    return (f"<div style='color:{color};font-size:11pt;font-weight:bold;"
            f"margin-bottom:4px;'>{v.icon} {v.headline}</div>"
            f"<ul style='margin:0 0 8px 0;color:#b9c0c7;'>{items}</ul>")
